export function installQualityGates() {
  for (const [from, to] of GATE_FILES) {
    if (place(from, to) !== 'kept') ctx.formatted.push(to)
  }
  placeText('eslint.ai-docs.js', ESLINT_AI_DOCS)
  ctx.formatted.push('eslint.ai-docs.js')
  mergeSettings()
  placeCodeowners()
}

function mergeSettings() {
  const rel = '.claude/settings.json'
  const wanted = readJson(join(SRC, 'docs/examples/claude-settings.hooks.json'))
  const abs = join(ctx.target, rel)
  if (!existsSync(abs)) {
    if (!ctx.args.dryRun) write(rel, JSON.stringify(wanted, null, 2) + '\n')
    return log('created', rel, 'hooks for the no-suppression check, format and lint after an edit, the UI lock, and migrations; deny rules for .env files')
  }
  const original = readFileSync(abs, 'utf8')
  const current = JSON.parse(original)
  const added = addMissingHooks(current, wanted)
  // Deny rules keep agents from reading real secrets (docs/03-standards/environment.md, "Agents and .env").
  current.permissions ??= {}
  current.permissions.deny ??= []
  const denied = wanted.permissions.deny.filter((rule) => !current.permissions.deny.includes(rule))
  current.permissions.deny.push(...denied)
  if (added.length === 0 && denied.length === 0) return log('unchanged', rel, 'hooks and deny rules already present')
  writeJsonLike(rel, original, current)
  const changes = [
    added.length > 0 ? `added the ${[...new Set(added)].join(' and ')} hook` : '',
    denied.length > 0 ? `added ${denied.length} deny rule(s) for .env files` : '',
  ].filter(Boolean)
  log('updated', rel, `${changes.join(', ')}, your settings kept`)
}

/** Adds each wanted hook whose command is not configured yet. Returns the events that got one. */
function addMissingHooks(current, wanted) {
  current.hooks ??= {}
  const added = []
  for (const [event, groups] of Object.entries(wanted.hooks)) {
    current.hooks[event] ??= []
    for (const group of groups) {
      const command = group.hooks[0].command
      if (current.hooks[event].some((g) => (g.hooks ?? []).some((h) => h.command === command))) continue
      current.hooks[event].push(group)
      added.push(event)
    }
  }
  return added
}

function placeCodeowners() {
  const rel = '.github/CODEOWNERS'
  let text = readFileSync(join(SRC, 'docs/examples/CODEOWNERS.example'), 'utf8')
  if (ctx.args.owner) text = text.replaceAll(OWNER_PLACEHOLDER, ctx.args.owner)
  const branchProtection = 'then turn on "Require review from Code Owners" in the repository branch protection (a GitHub setting).'
  // Owners are yours: once the file exists it is never rewritten (only --force replaces it, with a backup).
  if (existsSync(join(ctx.target, rel)) && !ctx.args.force) {
    if (readFileSync(join(ctx.target, rel), 'utf8').includes(OWNER_PLACEHOLDER)) {
      ctx.manual.push(`.github/CODEOWNERS still has the placeholder owner ${OWNER_PLACEHOLDER}: replace it, ${branchProtection}`)
    }
    return log('unchanged', rel, 'exists; owners are yours')
  }
  const action = placeContent(rel, Buffer.from(text), 'docs/examples/CODEOWNERS.example')
  if (action !== 'kept' && !ctx.args.owner) {
    ctx.manual.push(`.github/CODEOWNERS still has the placeholder owner ${OWNER_PLACEHOLDER}: replace it (or re-run with --owner @org/team), ${branchProtection}`)
  }
}
